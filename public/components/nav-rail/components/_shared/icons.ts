export function getIcon(name: string): string {
  // 1. Local lookup
  if ((ICONS as any)[name]) return (ICONS as any)[name];
  // 2. Registry lookup (namespace:name)
  if (name.includes(':')) {
    try {
      const svg = registryGet(name);
      if (svg) return svg;
    } catch { /* ignore */ }
  }
  // 3. Resolve short name across namespaces
  try {
    const nsList = registryListNs();
    for (const ns of nsList) {
      const svg = registryGet(ns + ':' + name);
      if (svg) return svg;
    }
  } catch { /* ignore */ }
  // 4. Default
  return (ICONS as any).default || '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"/></svg>';
}

export function hasIcon(name: string) {
    return !!(ICONS as Record<string, string>)[name];
}

export function listIcons() {
    return Object.keys(ICONS).filter(k => k !== 'default');
}

export default { ICONS, getIcon, hasIcon, listIcons, VERSION, MODULE_ID };
